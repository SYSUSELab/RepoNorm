"""Conservative, versioned Python file-role and module observations."""

from __future__ import annotations

from pathlib import PurePosixPath
from typing import Iterable

from repo_constraint_memory_v3.observations.models import (
    FileRoleObservation,
    ModuleIdentity,
)

ROLE_VERSION = "python-file-role-1.0"

_TEST_SEGMENTS = {"test", "tests"}
_EXAMPLE_SEGMENTS = {"example", "examples", "sample", "samples", "demos"}
_MIGRATION_SEGMENTS = {"migration", "migrations"}
_THIRD_PARTY_SEGMENTS = {"third_party", "_vendor", "vendored"}
_DEPRECATED_SEGMENTS = {"deprecated", "legacy"}
_GENERATED_NAMES = {
    "_version.py",
    "version.py",
    "generated.py",
    "_generated.py",
}
_GENERATED_MARKERS = (
    "generated file",
    "auto-generated",
    "autogenerated",
    "do not edit",
)
_DEPRECATED_MARKERS = ("deprecated module", "this module is deprecated")


def _segment_signals(path: str) -> list[tuple[str, str]]:
    pure = PurePosixPath(path)
    folded_parts = [part.casefold() for part in pure.parts[:-1]]
    folded_name = pure.name.casefold()
    signals: list[tuple[str, str]] = []
    if (
        set(folded_parts) & _TEST_SEGMENTS
        or folded_name.startswith("test_")
        or folded_name.endswith("_test.py")
        or folded_name.endswith("_test.pyi")
    ):
        signals.append(("test", "path:test_convention"))
    if set(folded_parts) & _EXAMPLE_SEGMENTS:
        signals.append(("example", "path:example_directory"))
    if set(folded_parts) & _MIGRATION_SEGMENTS or (
        "versions" in folded_parts and "migrations" in folded_parts
    ):
        signals.append(("migration", "path:migration_directory"))
    if set(folded_parts) & _THIRD_PARTY_SEGMENTS:
        signals.append(("third_party", "path:third_party_directory"))
    return signals


def observe_file_role(
    path: str,
    *,
    header_lines: Iterable[str],
    package_chain: bool,
    unique_src_root: bool,
) -> FileRoleObservation:
    signals = _segment_signals(path)
    if not signals and (package_chain or unique_src_root):
        signals.append(
            (
                "production",
                "package:init_chain" if package_chain else "layout:unique_src_root",
            )
        )
    roles = {role for role, _ in signals}
    if len(roles) == 1:
        location_role = next(iter(roles))
        classification_status = "exact"
    elif len(roles) > 1:
        location_role = "unknown"
        classification_status = "ambiguous"
    else:
        location_role = "unknown"
        classification_status = "unknown"

    pure = PurePosixPath(path)
    folded_parts = {part.casefold() for part in pure.parts}
    header = "\n".join(header_lines).casefold()
    attributes: list[str] = []
    basis = [reason for _, reason in signals]
    if pure.name.casefold() in _GENERATED_NAMES:
        attributes.append("generated")
        basis.append("filename:generated_allowlist")
    elif any(marker in header for marker in _GENERATED_MARKERS):
        attributes.append("generated")
        basis.append("header:generated_marker")
    if folded_parts & _DEPRECATED_SEGMENTS:
        attributes.append("deprecated")
        basis.append("path:deprecated_directory")
    elif any(marker in header for marker in _DEPRECATED_MARKERS):
        attributes.append("deprecated")
        basis.append("header:deprecated_marker")
    if not basis:
        basis.append("no_direct_role_signal")
    return FileRoleObservation(
        role_version=ROLE_VERSION,
        location_role=location_role,  # type: ignore[arg-type]
        classification_status=classification_status,  # type: ignore[arg-type]
        attributes=sorted(set(attributes)),  # type: ignore[arg-type]
        basis=sorted(set(basis)),
    )


def observe_module_identity(
    path: str,
    *,
    all_paths: set[str],
) -> ModuleIdentity:
    pure = PurePosixPath(path)
    without_suffix = pure.with_suffix("")
    parts = list(without_suffix.parts)
    source_root: str | None = None
    basis: list[str] = []
    ambiguous = False
    if parts and parts[0] == "src":
        source_root = "src"
        parts = parts[1:]
        basis.append("layout:src_root")
    if parts and parts[-1] == "__init__":
        parts = parts[:-1]
    package_dirs = list(pure.parent.parts)
    if source_root == "src" and package_dirs and package_dirs[0] == "src":
        package_dirs = package_dirs[1:]
    chain = []
    prefix = PurePosixPath(source_root) if source_root else PurePosixPath()
    for part in package_dirs:
        prefix = prefix / part
        init_py = (prefix / "__init__.py").as_posix()
        if init_py in all_paths:
            chain.append(part)
        else:
            ambiguous = bool(package_dirs)
            break
    if chain:
        basis.append("package:init_chain")
    if not parts:
        module_name = ".".join(chain) or None
    elif source_root == "src" or chain:
        module_name = ".".join(parts)
    else:
        module_name = None
        ambiguous = bool(pure.parent.parts)
    if module_name is not None and not ambiguous:
        status = "exact"
    elif ambiguous:
        status = "ambiguous"
        basis.append("namespace_or_source_root_ambiguous")
    else:
        status = "unknown"
        basis.append("no_module_identity_signal")
    return ModuleIdentity(
        module_name=module_name,
        package_parts=chain,
        source_root=source_root,
        resolution_status=status,  # type: ignore[arg-type]
        basis=sorted(set(basis)),
    )
